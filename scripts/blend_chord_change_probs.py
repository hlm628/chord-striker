"""
Blend several chord_change_probs.yaml files into one.

Each row (the probabilities of moving from one chord to the next) is
normalised in every source, then combined as a weighted average. The
"start" row (the first chord of a section) can instead be taken from a
single source, since sources define it differently (e.g. Hook Theory's is
the start of a progression, the Billboard data's is the start of a section).

Example:
    python scripts/blend_chord_change_probs.py \\
        --source constants/hooktheory/chord_change_probs.yaml 0.5 \\
        --source constants/mcgill_billboard/chord_change_probs.yaml 0.5 \\
        --start-from constants/mcgill_billboard/chord_change_probs.yaml \\
        --output chord_striker/constants/defaults/chord_change_probs.yaml
"""

from pathlib import Path

import click
import yaml


def normalise(row):
    total = sum(row.values())
    return {k: v / total for k, v in row.items()} if total > 0 else {}


def blend_rows(rows_and_weights):
    """Weighted average of normalised rows; sources lacking the row are skipped."""
    present = [(normalise(row), w) for row, w in rows_and_weights if row]
    total_weight = sum(w for _, w in present)
    blended = {}
    for row, w in present:
        for chord, p in row.items():
            blended[chord] = blended.get(chord, 0) + p * w / total_weight
    return blended


def blend(sources, start_from=None, min_percent=0.1):
    tables = [
        (yaml.safe_load(Path(path).read_text()), weight) for path, weight in sources
    ]
    row_names = {name for table, _ in tables for name in table}

    result = {}
    for name in row_names:
        if name == "start" and start_from is not None:
            result[name] = normalise(
                yaml.safe_load(Path(start_from).read_text())["start"]
            )
        else:
            result[name] = blend_rows([(table.get(name), w) for table, w in tables])

    # every chord we can move to needs its own row to move on from, so drop
    # any that don't have one, and very rare transitions
    for name, row in result.items():
        row = {c: p for c, p in row.items() if c in result and c != "start"}
        row = {c: p for c, p in normalise(row).items() if 100 * p >= min_percent}
        result[name] = {
            c: round(100 * p, 1)
            for c, p in sorted(normalise(row).items(), key=lambda kv: -kv[1])
        }

    # match the existing file layout: "start" first, then rows in name order
    return {"start": result.pop("start"), **dict(sorted(result.items()))}


@click.command()
@click.option(
    "--source",
    "sources",
    type=(click.Path(exists=True), float),
    multiple=True,
    required=True,
    help="A chord_change_probs.yaml file and its weight (repeatable)",
)
@click.option(
    "--start-from",
    type=click.Path(exists=True),
    default=None,
    help="Take the 'start' row from this file only, instead of blending it",
)
@click.option(
    "--min-percent",
    default=0.1,
    help="Drop transitions less likely than this percentage (default: 0.1)",
)
@click.option("--output", type=click.Path(), required=True, help="File to write")
def main(sources, start_from, min_percent, output):
    """Blend chord change probability tables from several sources."""
    blended = blend(sources, start_from, min_percent)
    header = "# Generated by scripts/blend_chord_change_probs.py from:\n" + "".join(
        f"#   {path} (weight {weight})\n" for path, weight in sources
    )
    if start_from:
        header += f"# 'start' row taken from {start_from}\n"
    with open(output, "w") as f:
        f.write(header)
        yaml.safe_dump(blended, f, sort_keys=False, default_flow_style=False)
    print(f"Wrote {output} ({len(blended)} rows)")


if __name__ == "__main__":
    main()
